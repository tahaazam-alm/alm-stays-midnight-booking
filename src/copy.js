export function useCopy() {
  const { lang } = useProto()
  const t = (key, ...args) => {
    const v = copy[lang]?.[key] ?? copy.en[key] ?? key
    return typeof v === 'function' ? v(...args) : v
  }
  // Mock data is written in English; in Arabic, look the string up in DATA_AR (falls back to the English)
  t.d = (s) => (lang === 'ar' && s != null ? DATA_AR[s] ?? s : s)
  t.lang = lang
  t.dir = lang === 'ar' ? 'rtl' : 'ltr' // for DS parts that read `dir` only from their props (Cell)
  return t
}
